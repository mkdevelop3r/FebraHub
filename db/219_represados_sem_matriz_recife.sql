-- FebraHub · Migration 219 — Represados só de Salvador (exclui matriz Recife)
--
-- Regra (decisão do gestor): a lista de represados de Salvador não pode incluir
-- alunos cuja VENDA tem "Unidade Realizadora do Curso (Matriz)" = FEBRACIS
-- RECIFE / RECIFE 2 — mesmo que a venda tenha sido gerada por Salvador 2. É um
-- atributo POR VENDA (Opportunity.Unidade__c → Coligada__c), não por turma: a
-- mesma turma tem vendas de matrizes diferentes. Ex. medido em 30/09/2026: 262
-- vendas geradas por Salvador 2 com matriz Recife (183 de Método CIS Global,
-- além de FOP, ML5, IF, FCIS, Master, BHP...).
--
-- Implementação:
--   1) fato_base_alunos ganha `unidade_realizadora_matriz` (populado pelo ETL
--      salesforce_api_sync a partir de Opportunity.Unidade__r.Name).
--   2) backfill imediato das vendas Recife conhecidas (efeito hoje, sem esperar
--      o próximo ETL). NULL = tratado como NÃO-Recife (mantém).
--   3) vw_pedagogico_prazo passa a excluir o represado cuja venda é 100% matriz
--      Recife (bool_and) — mantém quem tem ao menos uma venda não-Recife. Como
--      todas as views de prazo (salvador/resumo/pessoa/sem_contato) e a
--      fila_prazo/represados saem daqui, o corte vale pra tudo de uma vez.
-- ============================================================

